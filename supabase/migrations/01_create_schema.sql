-- 1. TABEL CATEGORIES (Publik bisa membaca katalog kategori)
CREATE TABLE IF NOT EXISTS categories (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL UNIQUE,
    image_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Public read categories" ON categories;
CREATE POLICY "Public read categories" ON categories FOR SELECT USING (true);

-- 2. ALTER TABEL EXISTING (products & product_variants)
-- Hasil inspeksi live DB: products.id = UUID, product_variants.id = UUID
ALTER TABLE products 
ADD COLUMN IF NOT EXISTS category_id UUID REFERENCES categories(id) ON DELETE SET NULL;

ALTER TABLE product_variants 
ADD COLUMN IF NOT EXISTS stock INT NOT NULL DEFAULT 100;

-- Kebijakan RLS Idempotent untuk products & product_variants
ALTER TABLE products ENABLE ROW LEVEL SECURITY;
DO $$ 
BEGIN 
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'products' AND policyname = 'Public read products') THEN
        CREATE POLICY "Public read products" ON products FOR SELECT USING (true);
    END IF;
END $$;

ALTER TABLE product_variants ENABLE ROW LEVEL SECURITY;
DO $$ 
BEGIN 
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'product_variants' AND policyname = 'Public read product_variants') THEN
        CREATE POLICY "Public read product_variants" ON product_variants FOR SELECT USING (true);
    END IF;
END $$;


