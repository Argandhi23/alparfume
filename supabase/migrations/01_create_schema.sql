-- ========================================================
-- POSTGRES FUNCTIONS (ATOMIC STOCK OPERATIONS - UUID VARIANT ID)
-- ========================================================

CREATE OR REPLACE FUNCTION deduct_product_stock(
    p_variant_id UUID,
    p_qty INT,
    p_order_id BIGINT
) RETURNS BOOLEAN AS $$
DECLARE
    v_updated_rows INT;
BEGIN
    UPDATE product_variants
    SET stock = stock - p_qty
    WHERE id = p_variant_id AND stock >= p_qty;
    
    GET DIAGNOSTICS v_updated_rows = ROW_COUNT;
    
    IF v_updated_rows > 0 THEN
        INSERT INTO stock_movements (variant_id, change_qty, reason, reference_order_id)
        VALUES (p_variant_id, -p_qty, 'order', p_order_id);
        RETURN TRUE;
    ELSE
        RETURN FALSE;
    END IF;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION restore_product_stock(
    p_variant_id UUID,
    p_qty INT,
    p_order_id BIGINT,
    p_reason VARCHAR
) RETURNS VOID AS $$
BEGIN
    UPDATE product_variants
    SET stock = stock + p_qty
    WHERE id = p_variant_id;
    
    INSERT INTO stock_movements (variant_id, change_qty, reason, reference_order_id)
    VALUES (p_variant_id, p_qty, COALESCE(p_reason, 'cancellation'), p_order_id);
END;
$$ LANGUAGE plpgsql;
